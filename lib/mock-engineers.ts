export function getAvatarClasses(color: string): { bg: string; text: string } {
  const colorMap = AVATAR_COLORS.reduce(
    (acc, c) => {
      const key = c.bg.replace('bg-', '').replace('-100', '');
      acc[key] = c;
      return acc;
    },
    {} as Record<string, { bg: string; text: string }>
  );
  return colorMap[color] || AVATAR_COLORS[0];
}
